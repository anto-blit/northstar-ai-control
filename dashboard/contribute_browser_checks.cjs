// Offline browser fixtures only. No real AI call, email or submission.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
module.exports = async ({call, navigate, evaluate, viewport, screenshot, homeURL, folder, pause}) => {
  const url = new URL('contribute.html', homeURL).href;
  await navigate(url);
  assert.match(await evaluate(`document.querySelector('noscript').textContent`), /one sentence/);
  assert.equal(await evaluate(`document.getElementById('onboarding').hidden`), true);
  await call('Emulation.setScriptExecutionDisabled', {value: false});
  await navigate(homeURL); await navigate(url);
  const screenshots = async stage => {
    for (const width of [320, 390, 768, 1440]) {
      await viewport(width, 1000);
      assert.equal(await evaluate(`document.documentElement.scrollWidth <= ${width}`), true, stage + ' overflow');
      await screenshot('guided-' + stage + '-' + width + '.png');
    }
  };
  await screenshots('start');
  await evaluate(`document.getElementById('start-form').requestSubmit()`);
  assert.equal(await evaluate(`document.getElementById('check-panel').hidden`), true);
  await evaluate(`document.getElementById('app-model').value='Browser fixture — model unknown'; document.getElementById('start-form').requestSubmit()`);
  const packet = JSON.parse(fs.readFileSync(path.join(__dirname, 'contributor-check-inputs.json'), 'utf8'));
  assert.equal(await evaluate(`document.getElementById('check-prompt').value`), packet.cases[0].prompt);
  await evaluate(`Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async text=>{window.checkCopied=text}}}); document.getElementById('copy-check').click()`);
  assert.equal(await evaluate(`window.checkCopied`), packet.cases[0].prompt);
  await evaluate(`document.getElementById('reply-form').requestSubmit()`);
  assert.match(await evaluate(`document.getElementById('reply-error').textContent`), /Paste the full reply/);
  const reply = '<label>NON_COMPLIANT</label> Browser fixture & literal text? #1';
  await evaluate(`document.getElementById('check-answer').value=${JSON.stringify(reply)}; document.getElementById('check-answer').dispatchEvent(new Event('input',{bubbles:true}))`);
  const id = await evaluate(`JSON.parse(sessionStorage.getItem('northstar-contribution-chat-check-v1')).record.id`);
  await navigate(homeURL); await navigate(url);
  assert.equal(await evaluate(`document.getElementById('check-answer').value`), reply);
  assert.equal(await evaluate(`JSON.parse(sessionStorage.getItem('northstar-contribution-chat-check-v1')).record.id`), id);
  await evaluate(`document.getElementById('reply-form').requestSubmit()`);
  assert.equal(await evaluate(`document.getElementById('check-prompt').value`), packet.cases[1].prompt);
  assert.match(await evaluate(`document.getElementById('chat-instruction').textContent`), /separate fresh chat/);
  await evaluate(`Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async()=>{throw new Error('denied')}}}); document.getElementById('copy-check').click()`);
  assert.equal(await evaluate(`document.getElementById('prompt-details').open`), true);
  assert.equal(await evaluate(`document.activeElement.id`), 'check-prompt');
  await screenshots('check');
  const control = '<label>COMPLIANT</label> Browser control fixture.';
  await evaluate(`document.getElementById('check-answer').value=${JSON.stringify(control)}; document.getElementById('reply-form').requestSubmit()`);
  assert.match(await evaluate(`document.getElementById('report-summary').textContent`), /2 of 2 replies/);
  const email = new URL(await evaluate(`document.getElementById('send-report').href`));
  assert.equal(email.pathname, 'info@calibratedvision.com');
  assert.ok(email.searchParams.get('body').includes(reply));
  assert.ok(email.searchParams.get('body').includes(control));
  await evaluate(`document.getElementById('copy-report').click()`);
  assert.equal(await evaluate(`document.activeElement.id`), 'report-text');
  assert.ok((await evaluate(`document.getElementById('report-text').value`)).includes(packet.cases[0].prompt));
  await evaluate(`document.getElementById('report-panel').scrollIntoView()`);
  await screenshots('report');
  const longReply = 'Long browser fixture <b>not markup</b> & '.repeat(2000);
  await evaluate(`document.getElementById('edit-report').click(); document.getElementById('check-answer').value=${JSON.stringify(longReply)}; document.getElementById('reply-form').requestSubmit()`);
  assert.match(await evaluate(`document.getElementById('share-instructions').textContent`), /too long/);
  assert.equal(await evaluate(`document.querySelector('#report-panel b')`), null);
  await evaluate(`document.getElementById('download-report').click()`);
  const reportPath = path.join(folder, id + '.txt');
  for (let i = 0; i < 100 && !fs.existsSync(reportPath); i++) await pause(50);
  const fullReport = fs.readFileSync(reportPath, 'utf8');
  for (const text of [longReply, packet.cases[0].prompt, packet.cases[1].prompt]) assert.ok(fullReport.includes(text));
  await evaluate(`sessionStorage.removeItem('northstar-contribution-chat-check-v1')`);
  await navigate(homeURL); await navigate(url);
  await evaluate(`document.getElementById('app-model').value='Unavailable fixture'; document.getElementById('start-form').requestSubmit(); document.getElementById('no-answer').click(); document.getElementById('reply-form').requestSubmit(); document.getElementById('stop-check').click()`);
  assert.match(await evaluate(`document.getElementById('report-summary').textContent`), /0 of 2 replies.*partial/);
  assert.match(await evaluate(`document.getElementById('report-text').value`), /no_answer/);
  assert.match(await evaluate(`document.getElementById('report-text').value`), /not_recorded/);
  await evaluate(`sessionStorage.removeItem('northstar-contribution-chat-check-v1')`);
  await navigate(homeURL); await navigate(url + '#idea');
  assert.equal(await evaluate(`document.getElementById('human-panel').hidden`), false);
  assert.match(await evaluate(`document.getElementById('intro-title').textContent`), /One sentence/);
  await evaluate(`document.getElementById('human-form').requestSubmit()`);
  assert.equal(await evaluate(`document.getElementById('report-panel').hidden`), true);
  await screenshots('idea');
  await evaluate(`document.getElementById('human-lesson').value='State which tasks remain, even if the news is disappointing.'; document.getElementById('human-form').requestSubmit()`);
  assert.match(await evaluate(`document.getElementById('report-text').value`), /UNTESTED/);
  assert.match(await evaluate(`document.getElementById('report-text').value`), /State which tasks remain/);
};
